"""Generates lib/features/player/domain/subtitle_code_pages.dart, the code
pages subtitle files that are not Unicode are read in (subtitle_cues.dart).

Run from the repository root:

    python3 -I tool/subtitle_code_pages.py > lib/features/player/domain/subtitle_code_pages.dart

It reads nothing but Python's own codecs, whose single-byte Windows tables
have not changed in years, and test/features/player/subtitle_cues_test.dart
checks the file against this script.

Each table is what the bytes 0x80 to 0xFF stand for, as Unicode code points;
everything below 0x80 is ASCII in all of them. A byte a code page leaves
undefined is written as U+FFFD, the replacement character.
"""
import sys

OUTPUT = 'lib/features/player/domain/subtitle_code_pages.dart'

# libVLC's name for each code page (--subsdec-encoding takes these, and they
# are what the setting stores), Python's, and who writes in it.
CODE_PAGES = [
    ('Windows-1250', 'cp1250', 'Central European'),
    ('Windows-1251', 'cp1251', 'Cyrillic'),
    ('Windows-1252', 'cp1252', 'Western'),
    ('Windows-1253', 'cp1253', 'Greek'),
    ('Windows-1254', 'cp1254', 'Turkish'),
    ('Windows-1255', 'cp1255', 'Hebrew'),
    ('Windows-1256', 'cp1256', 'Arabic'),
    ('Windows-1257', 'cp1257', 'Baltic'),
    ('Windows-1258', 'cp1258', 'Vietnamese'),
]

REPLACEMENT = 0xFFFD


def high_half(codec):
    """The code points of the bytes 0x80 to 0xFF in codec."""
    points = []
    for byte in range(0x80, 0x100):
        try:
            text = bytes([byte]).decode(codec)
        except UnicodeDecodeError:
            points.append(REPLACEMENT)
            continue
        assert len(text) == 1, (codec, byte, text)
        points.append(ord(text))
    return points


def main():
    w = sys.stdout.write
    w("// GENERATED by tool/subtitle_code_pages.py from Python's codecs. "
      'Do not edit.\n')
    w('// To regenerate, from the repository root:\n')
    w('// python3 -I tool/subtitle_code_pages.py > %s\n' % OUTPUT)
    w('\n')
    w('/// What the bytes 0x80 to 0xFF stand for in each Windows code page a\n')
    w('/// subtitle file is written in, as Unicode code points, keyed by the\n')
    w("/// name libVLC takes for it (`--subsdec-encoding`). Below 0x80 every one\n")
    w('/// of them is ASCII. A byte a code page leaves undefined is U+FFFD.\n')
    w('const Map<String, List<int>> subtitleCodePages = {\n')
    for name, codec, script in CODE_PAGES:
        w("  // %s\n" % script)
        w("  '%s': [\n" % name)
        points = high_half(codec)
        for row in range(0, len(points), 8):
            w('    %s, //\n' % ', '.join(
                '0x%04X' % point for point in points[row:row + 8]))
        w('  ],\n')
    w('};\n')


if __name__ == '__main__':
    main()
